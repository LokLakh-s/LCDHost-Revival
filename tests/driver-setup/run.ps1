# Installs, reinstalls and removes the G19 WinUSB driver with
# LCDHostDriverSetup, and checks the driver store and the certificate stores
# after each step. No device is needed: without a G19 the package waits in
# the driver store. Needs administrator rights; it changes the machine, so
# run it on a CI runner or a throwaway virtual machine.
# Usage: pwsh tests/driver-setup/run.ps1 <path to LCDHostDriverSetup.exe>
param([Parameter(Mandatory)][string]$Exe)

$ErrorActionPreference = 'Stop'
$Inf = 'lcdhost_g19_winusb.inf'
$Subject = 'CN=LCDHost G19 WinUSB driver (libwdi autogenerated)'

function Invoke-DriverSetup([string]$Command) {
    $log = Join-Path $env:TEMP "LCDHostDriverSetup-$Command.log"
    Write-Output "> LCDHostDriverSetup $Command"
    $process = Start-Process -FilePath $Exe -ArgumentList $Command, '--log', "`"$log`"" -Wait -PassThru -NoNewWindow
    if (Test-Path $log) { Get-Content $log | ForEach-Object { "  $_" } }
    if ($process.ExitCode -ne 0) { throw "$Command failed with exit code $($process.ExitCode)" }
}

function Get-Packages { @(pnputil /enum-drivers | Select-String -SimpleMatch $Inf) }
function Get-Certificates {
    @(Get-ChildItem Cert:\LocalMachine\Root, Cert:\LocalMachine\TrustedPublisher |
        Where-Object Subject -eq $Subject)
}

Invoke-DriverSetup install
if ((Get-Packages).Count -ne 1) { throw "expected one $Inf package in the driver store" }
if ((Get-Certificates).Count -ne 2) { throw 'expected the certificate in the Root and TrustedPublisher stores' }

Invoke-DriverSetup install
if ((Get-Packages).Count -ne 1) { throw 'reinstalling must replace the package, not add one' }
if ((Get-Certificates).Count -ne 2) { throw 'reinstalling must replace the certificate, not add one' }

Invoke-DriverSetup uninstall
if ((Get-Packages).Count -ne 0) { throw 'a driver package is left after uninstall' }
if ((Get-Certificates).Count -ne 0) { throw 'a certificate is left after uninstall' }

Invoke-DriverSetup uninstall

Write-Output 'OK: the G19 driver installs, reinstalls and uninstalls cleanly'
